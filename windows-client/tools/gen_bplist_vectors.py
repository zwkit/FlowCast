#!/usr/bin/env python3
"""Regenerate test/vectors/bplist_vectors.h.

The binary-plist reader needs known-answer vectors that come from an
independent encoder, not from itself. Python's plistlib in FMT_BINARY mode is
the reference used here; UxPlay's plist_to_bin() emits the same format.

    python tools/gen_bplist_vectors.py
"""
import os

import plistlib

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "test",
                   "vectors", "bplist_vectors.h")

CASES = [
    # The exact shape of a SETUP #1 response from the receiver.
    ("kSetup1", {
        "timingPort": 63680,
        "eventPort": 0,
        "deviceID": "AA:BB:CC:DD:EE:FF",
    }),
    # The exact shape of a SETUP #2 response: one array of stream dicts.
    ("kStreams", {
        "streams": [
            {"type": 110, "dataPort": 7100},
            {"type": 96, "dataPort": 6100, "controlPort": 6200},
        ],
    }),
    # Every scalar type the reader claims to support, wide and narrow.
    ("kMixed", {
        "b": True,
        "f": False,
        "r": 0.16666666666666666,
        "big": 0x3fffffc,
        "neg": -5,
        "d": b"\x00\x01\xfe\xff",
        "nested": {"a": [1, "two", 3.5]},
    }),
    ("kEmpty", {}),
    ("kDeep", {"a": {"b": {"c": {"d": {"e": [1, 2, 3]}}}}}),
    # Non-ASCII strings take the UTF-16BE path. The device name we advertise in
    # SETUP is user-editable on Windows, so accented, CJK and astral (emoji)
    # code points all have to survive the round trip.
    ("kUnicode", {
        "name": "caf\u00e9 \u4e2d\u6587 \U0001f389",
        "ascii": "plain",
        "u15": "0123456789abcde",
    }),
]


def emit(f, name, obj):
    blob = plistlib.dumps(obj, fmt=plistlib.FMT_BINARY)
    hexed = blob.hex()
    f.write("// %s: %d bytes, produced by Python plistlib FMT_BINARY "
            "(independent reference)\n" % (name, len(blob)))
    f.write("static const unsigned char %s[] = {\n" % name)
    for i in range(0, len(hexed), 32):
        row = ",".join("0x" + hexed[j:j + 2]
                       for j in range(i, min(i + 32, len(hexed)), 2))
        f.write("    " + row + ",\n")
    f.write("};\n\n")


def main():
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", newline="\n") as f:
        f.write("// Binary-plist known-answer vectors. Generated by "
                "tools/gen_bplist_vectors.py\n")
        f.write("// using Python plistlib in FMT_BINARY mode; do not hand-edit.\n\n")
        for name, obj in CASES:
            emit(f, name, obj)
    print("wrote %s" % os.path.normpath(OUT))


if __name__ == "__main__":
    main()
